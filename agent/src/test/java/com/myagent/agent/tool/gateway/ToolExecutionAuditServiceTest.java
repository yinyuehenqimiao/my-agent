package com.myagent.agent.tool.gateway;

import com.myagent.framework.context.LoginUser;
import com.myagent.framework.tool.ToolDefinition;
import com.myagent.framework.tool.ToolInvocation;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

class ToolExecutionAuditServiceTest {

    private JdbcTemplate jdbc;
    private ToolExecutionAuditService audit;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:tool-audit;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("DROP ALL OBJECTS");
        jdbc.execute("CREATE TABLE operation_audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "operation VARCHAR,operator_id VARCHAR,target_type VARCHAR,target_id VARCHAR,trace_id VARCHAR,"
                + "tenant_id VARCHAR,detail VARCHAR,created_time TIMESTAMP)");
        audit = new ToolExecutionAuditService(jdbc);
    }

    @Test
    void persistsTraceTenantActorAndOutcomeWithoutPersistingToolInput() {
        ToolInvocation invocation = ToolInvocation.builder()
                .toolName("prepare_leave_request")
                .identity(LoginUser.builder().userId("employee-1").username("员工")
                        .tenantId("tenant-a").build())
                .source(ToolDefinition.Source.WORKFLOW)
                .input(Map.of("reason", "包含敏感病情", "phone", "13800000000"))
                .build();

        assertThat(audit.record(invocation, "trace-1", "BEFORE_EXECUTION", "READY", 0L)).isTrue();

        Map<String, Object> row = jdbc.queryForMap("SELECT * FROM operation_audit");
        assertThat(row.get("operator_id")).isEqualTo("employee-1");
        assertThat(row.get("tenant_id")).isEqualTo("tenant-a");
        assertThat(row.get("trace_id")).isEqualTo("trace-1");
        assertThat(String.valueOf(row.get("detail")))
                .contains("phase=BEFORE_EXECUTION", "source=WORKFLOW", "outcome=READY")
                .doesNotContain("敏感病情", "13800000000");
    }

    @Test
    void storageFailureReturnsFalseAndIncrementsObservableCounter() {
        jdbc.execute("DROP TABLE operation_audit");
        ToolInvocation invocation = ToolInvocation.builder().toolName("read_tool")
                .identity(LoginUser.builder().userId("u1").tenantId("default").build()).build();

        assertThat(audit.record(invocation, "trace-2", "COMPLETED", "SUCCESS", 12L)).isFalse();
        assertThat(audit.writeFailureCount()).isEqualTo(1L);
    }
}

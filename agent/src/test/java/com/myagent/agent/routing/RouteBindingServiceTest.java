package com.myagent.agent.routing;

import com.myagent.agent.tool.AgentToolCatalog;
import com.myagent.framework.context.ExecutionIdentity;
import com.myagent.framework.context.LoginUser;
import com.myagent.framework.exception.ClientException;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.beans.factory.ObjectProvider;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class RouteBindingServiceTest {

    private JdbcTemplate jdbc;
    private AgentToolCatalog toolCatalog;
    private RouteBindingService service;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:route-admin;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("DROP ALL OBJECTS");
        jdbc.execute("CREATE TABLE wf_route(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "route_key VARCHAR(128) NOT NULL,intent_code VARCHAR(64) NOT NULL,workflow_def_key VARCHAR(128),"
                + "react_config VARCHAR,tenant_id VARCHAR(64) NOT NULL,create_time TIMESTAMP,update_time TIMESTAMP,"
                + "CONSTRAINT uk_route_key UNIQUE(route_key),CONSTRAINT uk_route_tenant_intent UNIQUE(tenant_id,intent_code))");
        jdbc.execute("CREATE TABLE wf_definition(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "def_key VARCHAR(128),name VARCHAR(128),tenant_id VARCHAR(64),current_published_version_id BIGINT)");
        jdbc.execute("CREATE TABLE t_intent_node(id VARCHAR(20),intent_code VARCHAR(64),name VARCHAR(64),kind SMALLINT,"
                + "parent_code VARCHAR(64),enabled SMALLINT,deleted SMALLINT)");
        jdbc.execute("CREATE TABLE operation_audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "operation VARCHAR(64),operator_id VARCHAR(64),target_type VARCHAR(64),target_id VARCHAR(128),"
                + "tenant_id VARCHAR(64),detail VARCHAR,created_time TIMESTAMP)");
        jdbc.update("INSERT INTO t_intent_node VALUES('1','leave-approval','请假审批',3,NULL,1,0)");
        jdbc.update("INSERT INTO t_intent_node VALUES('2','open-analysis','开放分析',2,NULL,1,0)");
        jdbc.update("INSERT INTO wf_definition(def_key,name,tenant_id,current_published_version_id) VALUES('leave-approval','请假审批','tenant-a',10)");
        jdbc.update("INSERT INTO wf_definition(def_key,name,tenant_id,current_published_version_id) VALUES('draft-flow','草稿流程','tenant-a',NULL)");
        toolCatalog = mock(AgentToolCatalog.class);
        when(toolCatalog.supportsWorkflow("leave-approval")).thenReturn(true);
        @SuppressWarnings("unchecked") ObjectProvider<AgentToolCatalog> provider = mock(ObjectProvider.class);
        when(provider.getIfAvailable()).thenReturn(toolCatalog);
        service = new RouteBindingService(jdbc, provider);
    }

    @Test
    void listAndOptionsAreTenantScopedAndOnlyExposeRunnablePublishedWorkflows() {
        jdbc.update("INSERT INTO wf_route(route_key,intent_code,workflow_def_key,tenant_id) VALUES('tenant-a-leave','leave-approval','leave-approval','tenant-a')");
        jdbc.update("INSERT INTO wf_route(route_key,intent_code,react_config,tenant_id) VALUES('tenant-b-open','open-analysis','default','tenant-b')");

        assertThat(service.list(identity("tenant-a"))).extracting(RouteBindingService.RouteBinding::routeKey)
                .containsExactly("tenant-a-leave");
        assertThat(service.options(identity("tenant-a")).workflows())
                .extracting(RouteBindingService.Option::value).containsExactly("leave-approval");
    }

    @Test
    void savingWorkflowRequiresPublishedRuntimeSupportedDefinitionAndWritesAudit() {
        service.save("leave-route", new RouteBindingService.SaveRequest(
                "leave-approval", RouteBindingService.TargetType.WORKFLOW, "leave-approval"), identity("tenant-a"));

        assertThat(jdbc.queryForObject("SELECT tenant_id FROM wf_route WHERE route_key='leave-route'", String.class))
                .isEqualTo("tenant-a");
        assertThat(jdbc.queryForObject("SELECT operation FROM operation_audit", String.class))
                .isEqualTo("ROUTE_CREATE");

        assertThatThrownBy(() -> service.save("draft-route", new RouteBindingService.SaveRequest(
                "leave-approval", RouteBindingService.TargetType.WORKFLOW, "draft-flow"), identity("tenant-a")))
                .isInstanceOf(ClientException.class).hasMessageContaining("已发布");
    }

    @Test
    void duplicateIntentWithinTenantIsRejectedButOtherTenantIsAllowed() {
        service.save("route-a", new RouteBindingService.SaveRequest(
                "open-analysis", RouteBindingService.TargetType.REACT, "default"), identity("tenant-a"));

        assertThatThrownBy(() -> service.save("route-a-duplicate", new RouteBindingService.SaveRequest(
                "open-analysis", RouteBindingService.TargetType.REACT, "default"), identity("tenant-a")))
                .isInstanceOf(ClientException.class).hasMessageContaining("已绑定");

        service.save("route-b", new RouteBindingService.SaveRequest(
                "open-analysis", RouteBindingService.TargetType.REACT, "default"), identity("tenant-b"));
        assertThat(jdbc.queryForObject("SELECT count(*) FROM wf_route", Integer.class)).isEqualTo(2);
    }

    @Test
    void deleteCannotCrossTenantAndSuccessfulDeleteIsAudited() {
        service.save("route-a", new RouteBindingService.SaveRequest(
                "open-analysis", RouteBindingService.TargetType.REACT, "default"), identity("tenant-a"));

        assertThatThrownBy(() -> service.delete("route-a", identity("tenant-b")))
                .isInstanceOf(ClientException.class).hasMessageContaining("不存在");
        service.delete("route-a", identity("tenant-a"));

        assertThat(jdbc.queryForObject("SELECT count(*) FROM wf_route", Integer.class)).isZero();
        assertThat(jdbc.queryForObject("SELECT count(*) FROM operation_audit WHERE operation='ROUTE_DELETE'", Integer.class))
                .isEqualTo(1);
    }

    private ExecutionIdentity identity(String tenantId) {
        return LoginUser.builder().userId("admin-1").username("管理员").tenantId(tenantId).build();
    }
}

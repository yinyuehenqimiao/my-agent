package com.myagent.agent.routing;

import com.myagent.framework.context.LoginUser;
import com.myagent.framework.routing.RouteDecision;
import com.myagent.rag.enums.IntentKind;
import com.myagent.system.auth.service.PolicyDecisionService;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.test.context.junit.jupiter.SpringJUnitConfig;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;

import javax.sql.DataSource;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

/** 阶段 5 路由决策测试：年假入 Workflow / 制度入 RAG / 开放入 ReAct / 模糊入 CLARIFY / 高风险未授权 DENY / 待确认优先 / 降级。 */
@SpringJUnitConfig(RoutingServiceTest.Config.class)
class RoutingServiceTest {

    @Configuration
    @EnableTransactionManagement
    static class Config {
        @Bean(destroyMethod = "close") DataSource ds() {
            var ds = new com.zaxxer.hikari.HikariDataSource();
            ds.setJdbcUrl("jdbc:h2:mem:routing;MODE=PostgreSQL;DB_CLOSE_DELAY=-1;NON_KEYWORDS=YEAR,DAY");
            ds.setUsername("sa");
            ds.setPassword("");
            ds.setMaximumPoolSize(4);
            return ds;
        }

        @Bean JdbcTemplate jdbc(DataSource ds) { return new JdbcTemplate(ds); }

        @Bean PolicyDecisionService policy() { return mock(PolicyDecisionService.class); }

        @Bean RoutingService routingService(JdbcTemplate jdbc, PolicyDecisionService p) {
            return new RoutingService(jdbc, p);
        }

        @Bean PlatformTransactionManager tx(DataSource ds) { return new DataSourceTransactionManager(ds); }
    }

    @Autowired private JdbcTemplate jdbc;
    @Autowired private RoutingService routing;
    @Autowired private PolicyDecisionService policy;

    private com.myagent.framework.context.ExecutionIdentity identity(String userId) {
        return LoginUser.builder().userId(userId).username(userId).tenantId("default").build();
    }

    private com.myagent.framework.context.ExecutionIdentity identity(String userId, String tenantId) {
        return LoginUser.builder().userId(userId).username(userId).tenantId(tenantId).build();
    }

    @BeforeEach
    void setup() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS wf_route(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,route_key VARCHAR,intent_code VARCHAR,workflow_def_key VARCHAR,react_config VARCHAR,tenant_id VARCHAR,create_time TIMESTAMP,update_time TIMESTAMP)");
        jdbc.update("DELETE FROM wf_route");
        jdbc.update("INSERT INTO wf_route(route_key,intent_code,workflow_def_key,react_config,tenant_id) VALUES('r1','leave-approval','leave-approval',NULL,'default')");
        jdbc.update("INSERT INTO wf_route(route_key,intent_code,workflow_def_key,react_config,tenant_id) VALUES('r2','open-analysis',NULL,'default','default')");
        jdbc.update("INSERT INTO wf_route(route_key,intent_code,workflow_def_key,react_config,tenant_id) VALUES('r3','tenant-only','tenant-flow',NULL,'tenant-b')");
    }

    @Test
    void leaveApprovalRoutesToWorkflow() {
        var r = routing.route("leave-approval", IntentKind.WORKFLOW, 0.9, false, identity("e"));
        assertEquals(RouteDecision.WORKFLOW, r.getDecision());
        assertEquals("leave-approval", r.getTarget());
    }

    @Test
    void lowConfidenceWorkflowRoutesToClarify() {
        var r = routing.route("leave-approval", IntentKind.WORKFLOW, 0.5, false, identity("e"));
        assertEquals(RouteDecision.CLARIFY, r.getDecision());
    }

    @Test
    void knowledgeQuestionRoutesToSystem() {
        var r = routing.route("leave-policy", IntentKind.KB, 0.8, false, identity("e"));
        assertEquals(RouteDecision.SYSTEM, r.getDecision());
    }

    @Test
    void systemIntentRoutesToSystem() {
        var r = routing.route("greeting", IntentKind.SYSTEM, 0.9, false, identity("e"));
        assertEquals(RouteDecision.SYSTEM, r.getDecision());
    }

    @Test
    void openAnalysisRoutesToReactWhenAuthorized() {
        when(policy.hasPermission(any(), eq("workflow:submit"))).thenReturn(true);
        var r = routing.route("open-analysis", IntentKind.MCP, 0.7, false, identity("e"));
        assertEquals(RouteDecision.REACT, r.getDecision());
    }

    @Test
    void ambiguousLowConfidenceRoutesToClarify() {
        var r = routing.route("unknown-intent", IntentKind.MCP, 0.4, false, identity("e"));
        assertEquals(RouteDecision.CLARIFY, r.getDecision());
    }

    @Test
    void highRiskUnauthorizedDenied() {
        // leave-approval 是高风险前缀；未授权 workflow:submit → DENY
        when(policy.hasPermission(any(), eq("workflow:submit"))).thenReturn(false);
        var r = routing.route("leave-approval-open", IntentKind.MCP, 0.9, false, identity("e"));
        assertEquals(RouteDecision.DENY, r.getDecision());
    }

    @Test
    void missingIdentityDeniedForReact() {
        var r = routing.route("open-analysis", IntentKind.MCP, 0.9, false, null);
        assertEquals(RouteDecision.DENY, r.getDecision());
    }

    @Test
    void pendingActionPrecedesWorkflow() {
        // 即使低置信，有待确认动作也优先走 Workflow
        var r = routing.route("leave-approval", IntentKind.WORKFLOW, 0.3, true, identity("e"));
        assertEquals(RouteDecision.WORKFLOW, r.getDecision());
        assertEquals("leave-approval", r.getTarget());
    }

    @Test
    void modelUnavailableStillRoutesWorkflow() {
        // 路由不依赖模型自由规划：固定流程高置信仍路由到 Workflow（模拟模型不可用场景）
        var r = routing.route("leave-approval", IntentKind.WORKFLOW, 0.95, false, identity("e"));
        assertEquals(RouteDecision.WORKFLOW, r.getDecision());
    }

    @Test
    void promptInjectionCannotEscalateToWorkflow() {
        // 提示注入：模型试图路由到高风险写流程，但未授权 → DENY（Prompt 不承担权限判断）
        when(policy.hasPermission(any(), eq("workflow:submit"))).thenReturn(false);
        var r = routing.route("leave-approval-fake", IntentKind.MCP, 0.99, false, identity("attacker"));
        assertEquals(RouteDecision.DENY, r.getDecision());
    }

    @Test
    void routeStorageFailureMustNotFailOpenIntoReact() {
        jdbc.execute("DROP TABLE wf_route");

        assertThrows(DataAccessException.class,
                () -> routing.route("open-analysis", IntentKind.MCP, 0.99, false, identity("e")));
    }

    @Test
    void routeBindingUsesIdentityTenantInsteadOfDefaultTenant() {
        var tenantRoute = routing.route("tenant-only", IntentKind.WORKFLOW, 0.95, false,
                identity("employee-b", "tenant-b"));
        var otherTenantRoute = routing.route("tenant-only", IntentKind.WORKFLOW, 0.95, false,
                identity("employee-a", "tenant-a"));

        assertEquals(RouteDecision.WORKFLOW, tenantRoute.getDecision());
        assertEquals("tenant-flow", tenantRoute.getTarget());
        assertEquals(RouteDecision.CLARIFY, otherTenantRoute.getDecision());
    }
}

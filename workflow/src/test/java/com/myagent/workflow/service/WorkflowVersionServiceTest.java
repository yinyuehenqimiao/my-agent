package com.myagent.workflow.service;

import com.myagent.framework.exception.ClientException;
import com.myagent.workflow.dao.entity.WfVersionDO;
import com.myagent.workflow.enums.VersionStatus;
import com.myagent.workflow.validation.BpmnValidator;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.test.context.junit.jupiter.SpringJUnitConfig;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;

import javax.sql.DataSource;

import static org.junit.jupiter.api.Assertions.*;

/** 阶段 3 版本生命周期测试：草稿/审核/发布/退休/回滚、自审拦截、发布不可编辑。 */
@SpringJUnitConfig(WorkflowVersionServiceTest.Config.class)
class WorkflowVersionServiceTest {

    @Configuration
    @EnableTransactionManagement
    static class Config {
        @Bean(destroyMethod = "close") DataSource ds() {
            var ds = new com.zaxxer.hikari.HikariDataSource();
            ds.setJdbcUrl("jdbc:h2:mem:workflow;MODE=PostgreSQL;DB_CLOSE_DELAY=-1;NON_KEYWORDS=YEAR,DAY");
            ds.setUsername("sa");
            ds.setPassword("");
            ds.setMaximumPoolSize(4);
            return ds;
        }

        @Bean JdbcTemplate jdbc(DataSource ds) { return new JdbcTemplate(ds); }

        @Bean BpmnValidator bpmnValidator() { return new BpmnValidator(); }

        @Bean WorkflowVersionService versionService(JdbcTemplate jdbc, BpmnValidator v) {
            return new WorkflowVersionService(jdbc, v);
        }

        @Bean PlatformTransactionManager tx(DataSource ds) { return new DataSourceTransactionManager(ds); }
    }

    @Autowired private JdbcTemplate jdbc;
    @Autowired private WorkflowVersionService service;

    private static final String BPMN = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>"
            + "<definitions xmlns:flowable=\"http://flowable.org/bpmn\" xmlns=\"http://www.omg.org/spec/BPMN/20100524/MODEL\">"
            + "<process id=\"p1\" isExecutable=\"true\">"
            + "<startEvent id=\"s\"/><sequenceFlow id=\"f1\" sourceRef=\"s\" targetRef=\"e\"/><endEvent id=\"e\"/>"
            + "</process></definitions>";

    @BeforeEach
    void setup() {
        jdbc.execute("DROP ALL OBJECTS");
        jdbc.execute("CREATE TABLE wf_definition(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,def_key VARCHAR,name VARCHAR,description VARCHAR,tenant_id VARCHAR,current_published_version_id BIGINT,create_time TIMESTAMP,update_time TIMESTAMP)");
        jdbc.execute("CREATE TABLE wf_version(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,definition_id BIGINT,version_number INT,bpmn_xml CLOB,status VARCHAR,created_by VARCHAR,created_time TIMESTAMP,updated_time TIMESTAMP,published_time TIMESTAMP,published_by VARCHAR,parent_version_id BIGINT)");
        jdbc.execute("CREATE TABLE wf_review(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,version_id BIGINT,reviewer_id VARCHAR,action VARCHAR,comment VARCHAR,created_time TIMESTAMP)");
    }

    @Test
    void fullLifecycleDraftReviewPublishRetireRollback() {
        WfVersionDO v1 = service.createDraft("leave-approval", "请假审批", "desc", BPMN, "editor");
        assertEquals(VersionStatus.DRAFT.name(), v1.getStatus());
        assertEquals(1, v1.getVersionNumber());

        service.submitForReview(v1.getId(), "editor");
        service.review(v1.getId(), "reviewer", true, "ok");
        assertEquals(VersionStatus.APPROVED.name(), jdbc.queryForObject("SELECT status FROM wf_version WHERE id=?", String.class, v1.getId()));

        service.publish(v1.getId(), "publisher");
        assertEquals(VersionStatus.PUBLISHED.name(), jdbc.queryForObject("SELECT status FROM wf_version WHERE id=?", String.class, v1.getId()));
        assertEquals(v1.getId(), jdbc.queryForObject("SELECT current_published_version_id FROM wf_definition WHERE def_key=?", Long.class, "leave-approval"));

        // 回滚到已发布版本（仍为 PUBLISHED）
        service.rollback(v1.getDefinitionId(), v1.getId(), "publisher");
        assertEquals(v1.getId(), jdbc.queryForObject("SELECT current_published_version_id FROM wf_definition WHERE def_key=?", Long.class, "leave-approval"));

        service.retire(v1.getId(), "publisher");
        assertEquals(VersionStatus.RETIRED.name(), jdbc.queryForObject("SELECT status FROM wf_version WHERE id=?", String.class, v1.getId()));
        assertNull(jdbc.queryForObject("SELECT current_published_version_id FROM wf_definition WHERE def_key=?", Long.class, "leave-approval"));
    }

    @Test
    void editorCannotSelfReview() {
        WfVersionDO v = service.createDraft("k2", "n", "d", BPMN, "editor");
        service.submitForReview(v.getId(), "editor");
        ClientException ex = assertThrows(ClientException.class, () -> service.review(v.getId(), "editor", true, "self"));
        assertTrue(ex.getMessage().contains("不得审核自己"));
    }

    @Test
    void publishedVersionNotEditable() {
        WfVersionDO v = service.createDraft("k3", "n", "d", BPMN, "editor");
        service.submitForReview(v.getId(), "editor");
        service.review(v.getId(), "reviewer", true, "ok");
        service.publish(v.getId(), "publisher");
        ClientException ex = assertThrows(ClientException.class, () -> service.newVersionFrom(v.getId(), BPMN, "editor"));
        assertTrue(ex.getMessage().contains("不可编辑"));
    }

    @Test
    void newVersionFromDraftCreatesIncrementedVersion() {
        WfVersionDO v1 = service.createDraft("k4", "n", "d", BPMN, "editor");
        WfVersionDO v2 = service.newVersionFrom(v1.getId(), BPMN, "editor");
        assertEquals(2, v2.getVersionNumber());
        assertEquals(v1.getId(), v2.getParentVersionId());
    }

    @Test
    void rejectTransitionsToRejected() {
        WfVersionDO v = service.createDraft("k5", "n", "d", BPMN, "editor");
        service.submitForReview(v.getId(), "editor");
        service.review(v.getId(), "reviewer", false, "bad");
        assertEquals(VersionStatus.REJECTED.name(), jdbc.queryForObject("SELECT status FROM wf_version WHERE id=?", String.class, v.getId()));
    }

    @Test
    void publishWithInvalidBpmnFails() {
        WfVersionDO v = service.createDraft("k6", "n", "d", BPMN, "editor");
        service.submitForReview(v.getId(), "editor");
        service.review(v.getId(), "reviewer", true, "ok");
        // 将 BPMN 改为非法（缺结束节点），发布校验应失败
        String bad = "<?xml version=\"1.0\"?><definitions xmlns=\"http://www.omg.org/spec/BPMN/20100524/MODEL\"><process id=\"p1\"><startEvent id=\"s\"/></process></definitions>";
        jdbc.update("UPDATE wf_version SET bpmn_xml=? WHERE id=?", bad, v.getId());
        assertThrows(ClientException.class, () -> service.publish(v.getId(), "publisher"));
    }

    @Test
    void duplicateDefKeyRejected() {
        service.createDraft("dup", "n", "d", BPMN, "editor");
        assertThrows(ClientException.class, () -> service.createDraft("dup", "n2", "d", BPMN, "editor"));
    }

    @Test
    void rollbackToNonPublishedRejected() {
        WfVersionDO v = service.createDraft("k7", "n", "d", BPMN, "editor");
        assertThrows(ClientException.class, () -> service.rollback(v.getDefinitionId(), v.getId(), "op"));
    }
}

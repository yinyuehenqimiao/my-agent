package com.myagent.workflow.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.myagent.framework.exception.ClientException;
import com.myagent.workflow.model.WorkflowProcess;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;

class WorkflowProcessVersionServiceTest {
    private JdbcTemplate jdbc;
    private WorkflowProcessVersionService service;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:process-version;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("DROP ALL OBJECTS");
        jdbc.execute("CREATE TABLE wf_definition(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,def_key VARCHAR UNIQUE,name VARCHAR,description VARCHAR,tenant_id VARCHAR,create_time TIMESTAMP,update_time TIMESTAMP)");
        jdbc.execute("CREATE TABLE wf_version(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,definition_id BIGINT,version_number INT,bpmn_xml CLOB,process_json CLOB,content_hash VARCHAR,dependency_snapshot CLOB,source_type VARCHAR,lock_version BIGINT,status VARCHAR,created_by VARCHAR,created_time TIMESTAMP,updated_time TIMESTAMP,parent_version_id BIGINT,tested_content_hash VARCHAR,reviewed_content_hash VARCHAR)");
        service = new WorkflowProcessVersionService(jdbc, new ObjectMapper(), new WorkflowProcessCompiler());
    }

    @Test
    void createsJsonSourceAndPreventsConcurrentOverwrite() {
        var created = service.create("demo", "演示", null, process("首次回复"), "editor");
        assertNotNull(created.contentHash());
        assertEquals("PROCESS_JSON", jdbc.queryForObject("SELECT source_type FROM wf_version WHERE id=?", String.class, created.versionId()));

        var updated = service.updateDraft(created.versionId(), 0, process("修改回复"), "editor");
        assertEquals(1, updated.lockVersion());
        assertThrows(ClientException.class, () -> service.updateDraft(created.versionId(), 0, process("并发覆盖"), "editor"));
    }

    private WorkflowProcess process(String template) {
        return new WorkflowProcess(1,
                List.of(new WorkflowProcess.Node("s", "start", 1, Map.of()), new WorkflowProcess.Node("r", "reply", 1, Map.of("template", template)), new WorkflowProcess.Node("e", "end", 1, Map.of())),
                List.of(new WorkflowProcess.Edge("1", "s", "r", null, null), new WorkflowProcess.Edge("2", "r", "e", null, null)),
                List.of(), List.of());
    }
}
